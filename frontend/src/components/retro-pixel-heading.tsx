interface PixelTextProps {
  text: string;
  pixelSize?: number;
  gap?: number;
  color?: string;
  wireframe?: boolean;
  className?: string;
}

export function RetroPixelWord({
  text,
  pixelSize = 6,
  gap = 1,
  color = "#FFFFFF",
  wireframe = false,
  className = "",
}: PixelTextProps) {
  const chars = text.toUpperCase().split("");
  const charSpacing = pixelSize * 2;

  // Calculate width
  let totalWidth = 0;
  chars.forEach((c) => {
    const matrix = PIXEL_MAP[c] || PIXEL_MAP["E"];
    const cols = matrix[0].length;
    totalWidth += cols * (pixelSize + gap) + charSpacing;
  });
  const totalHeight = 7 * (pixelSize + gap);

  let currentX = 0;

  return (
    <svg
      width={totalWidth}
      height={totalHeight}
      viewBox={`0 0 ${totalWidth} ${totalHeight}`}
      className={`overflow-visible select-none inline-block ${className}`}
    >
      {chars.map((c, charIdx) => {
        const matrix = PIXEL_MAP[c] || PIXEL_MAP["E"];
        const charX = currentX;
        const cols = matrix[0].length;
        currentX += cols * (pixelSize + gap) + charSpacing;

        return (
          <g key={charIdx} transform={`translate(${charX}, 0)`}>
            {matrix.map((row, rIdx) =>
              row.map((cell, cIdx) => {
                if (!cell) return null;
                const x = cIdx * (pixelSize + gap);
                const y = rIdx * (pixelSize + gap);

                if (wireframe) {
                  return (
                    <rect
                      key={`${rIdx}-${cIdx}`}
                      x={x}
                      y={y}
                      width={pixelSize}
                      height={pixelSize}
                      fill="none"
                      stroke={color}
                      strokeWidth={1.5}
                    />
                  );
                }

                return (
                  <rect
                    key={`${rIdx}-${cIdx}`}
                    x={x}
                    y={y}
                    width={pixelSize}
                    height={pixelSize}
                    fill={color}
                  />
                );
              })
            )}
          </g>
        );
      })}
    </svg>
  );
}

interface PixelHeadingProps {
  prefix: string;
  pixelWord: string;
  subtitle?: string;
  wireframe?: boolean;
  className?: string;
}

export function RetroHeroTitle({
  prefix,
  pixelWord,
  subtitle,
  wireframe = false,
  className = "",
}: PixelHeadingProps) {
  return (
    <div className={`space-y-2 select-none ${className}`}>
      <h1 className="text-4xl sm:text-6xl md:text-7xl font-bold tracking-tight text-white leading-none">
        {prefix}
      </h1>
      <div className="pt-1">
        <RetroPixelWord
          text={pixelWord}
          pixelSize={8}
          gap={1.5}
          color={wireframe ? "#FFFFFF" : "#FFFFFF"}
          wireframe={wireframe}
        />
      </div>
      {subtitle && (
        <p className="text-sm md:text-base text-zinc-400 font-normal max-w-xl pt-4 leading-relaxed">
          {subtitle}
        </p>
      )}
    </div>
  );
}
